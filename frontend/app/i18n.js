  /** Traduzione con interpolazione di {segnaposto}. */
  const t = function t(chiave, valori) {
    let testo = (DIZIONARIO[LINGUA] && DIZIONARIO[LINGUA][chiave])
      ?? DIZIONARIO.it[chiave] ?? chiave;
    if (valori) {
      Object.keys(valori).forEach((nome) => {
        testo = testo.replaceAll(`{${nome}}`, valori[nome]);
      });
    }
    return testo;
  };

  /**
   * Numero e sostantivo insieme. La forma singolare ha la sua chiave, con il
   * suffisso `1`: in italiano e in inglese cambia la parola, non solo la `s`.
   */
  const n = function n(quantita, chiave, valori) {
    const numero = Number(quantita) || 0;
    return t(numero === 1 ? `${chiave}1` : chiave, { n: numero, ...(valori || {}) });
  };

